#!/usr/bin/env python3
"""audit.py — coverage-and-assumptions table for every paper claim, produced by Lean itself.
Copyright (C) Dave Goel 2026--now. Licensed under the Apache License 2.0; see LICENSE.

For every `theorem` in FejesTothP7/Paper/Statements.lean this script asks Lean (`#print axioms`)
which axioms the proof depends on, and classifies it:
  PROVED      only Lean's three standard axioms (propext, Classical.choice, Quot.sound)
  OPEN        depends on sorryAx (a proof gap somewhere below it)
  VIOLATION   any other axiom (forbidden; fails loudly)

Usage: scripts/audit.py            (writes AUDIT.md, exits 1 on any OPEN or VIOLATION)
       scripts/audit.py --test     (self-test of the parser and classifier)
"""
import re
import subprocess
import sys
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent
STATEMENTS = PROJECT / "FejesTothP7" / "Paper" / "Statements.lean"
AUDIT_LEAN = PROJECT / "FejesTothP7" / "Audit.lean"
AUDIT_MD = PROJECT / "AUDIT.md"
STANDARD = {"propext", "Classical.choice", "Quot.sound"}
NAMESPACE = "FejesTothP7.Paper"
TRUST_NOTE = (
    "**Trust.** Every row marked `PROVED` depends solely on Lean 4's three standard axioms "
    "(`propext`, `Classical.choice`, `Quot.sound`) — zero custom axioms, zero cited axioms, "
    "zero `sorry`, and zero computer checks. The trust surface a referee needs to read is "
    "`FejesTothP7/Defs/` and `FejesTothP7/Paper/Statements.lean`; every proof under "
    "`FejesTothP7/Proofs/` is machine-checked by Lean."
)


def parse_statements(text):
    """Return [(name, doc_first_line)] for every top-level theorem, in file order."""
    items = []
    for block in re.finditer(r"(/--(.*?)-/\s*)?^theorem\s+([\w']+)", text, re.S | re.M):
        doc = " ".join((block.group(2) or "").split())
        items.append((block.group(3), doc[:140]))
    return items


def write_audit_lean(names):
    lines = [
        "/-",
        "Copyright (C) Dave Goel 2026--now. Licensed under the Apache License 2.0; see LICENSE.",
        "-/",
        "-- GENERATED by scripts/audit.py — do not edit.",
        "import FejesTothP7.Paper.Statements",
        "",
    ]
    lines += [f"#print axioms {NAMESPACE}.{name}" for name in names]
    content = "\n".join(lines) + "\n"
    if not AUDIT_LEAN.exists() or AUDIT_LEAN.read_text() != content:
        AUDIT_LEAN.write_text(content)


def run_lean():
    proc = subprocess.run(
        ["nice", "-n", "19", "lake", "build", "FejesTothP7.Audit"],
        cwd=PROJECT,
        capture_output=True,
        text=True,
        env=None,
    )
    if proc.returncode != 0:
        sys.exit("AUDIT FAILED: Lean reported an error:\n" + proc.stdout + proc.stderr)
    return proc.stdout + proc.stderr


def parse_axioms(output, names):
    """Map each theorem name to its set of axioms, from `#print axioms` output."""
    result = {}
    pattern = re.compile(
        r"'([\w.']+)' (?:depends on axioms: \[(.*?)\]|does not depend on any axioms)", re.S
    )
    for match in pattern.finditer(output):
        full = match.group(1)
        short = full.removeprefix(NAMESPACE + ".")
        axioms = {
            a.strip() for a in (match.group(2) or "").replace("\n", " ").split(",") if a.strip()
        }
        result[short] = axioms
    missing = [n for n in names if n not in result]
    if missing:
        sys.exit(f"AUDIT FAILED: no #print axioms output for {missing}")
    return result


def classify(axioms):
    forbidden = axioms - STANDARD - {"sorryAx"}
    if forbidden:
        return "VIOLATION"
    if "sorryAx" in axioms:
        return "OPEN"
    return "PROVED"


def render(items, axioms_by_name):
    rows = ["| # | Lean name | Paper claim | Status | Axioms |", "|---|---|---|---|---|"]
    counts = {}
    for idx, (name, doc) in enumerate(items, 1):
        axioms = axioms_by_name[name]
        status = classify(axioms)
        counts[status] = counts.get(status, 0) + 1
        ax_list = ", ".join(sorted(axioms)) or "none"
        rows.append(f"| {idx} | `{name}` | {doc} | {status} | `{ax_list}` |")
    summary = ", ".join(f"{k}: {v}" for k, v in sorted(counts.items()))
    return summary, "\n".join(rows), counts


def main_audit():
    items = parse_statements(STATEMENTS.read_text())
    names = [n for n, _ in items]
    write_audit_lean(names)
    axioms_by_name = parse_axioms(run_lean(), names)
    summary, table, counts = render(items, axioms_by_name)
    AUDIT_MD.write_text(
        f"# AUDIT — every claim of the paper, as Lean sees it\n\n"
        f"Generated by `scripts/audit.py` from `#print axioms`. Summary: {summary}.\n\n"
        f"{TRUST_NOTE}\n\n{table}\n"
    )
    print(f"AUDIT: {len(items)} claims. {summary}. Table: AUDIT.md")
    if counts.get("VIOLATION") or counts.get("OPEN"):
        sys.exit(f"AUDIT FAILED: non-PROVED rows present ({summary}).")


def main_test():
    sample = (
        "/-- **Lemma 9.9**: hello. -/\ntheorem foo : True := trivial\n"
        "theorem bar : True := sorry\ntheorem qux' : True := trivial\n"
    )
    assert parse_statements(sample) == [
        ("foo", "**Lemma 9.9**: hello."),
        ("bar", ""),
        ("qux'", ""),
    ]
    out = (
        "'FejesTothP7.Paper.foo' depends on axioms: [propext,\n Classical.choice]\n"
        "'FejesTothP7.Paper.bar' depends on axioms: [sorryAx]\n"
        "'FejesTothP7.Paper.baz' does not depend on any axioms\n"
        "'FejesTothP7.Paper.qux'' does not depend on any axioms\n"
    )
    got = parse_axioms(out, ["foo", "bar", "baz", "qux'"])
    assert classify(got["qux'"]) == "PROVED"
    assert classify(got["foo"]) == "PROVED"
    assert classify(got["bar"]) == "OPEN"
    assert classify(got["baz"]) == "PROVED"
    assert classify({"propext", "evil"}) == "VIOLATION"
    assert classify({"sorryAx", "evil"}) == "VIOLATION"
    print("PASS: audit.py self-test")


def main():
    if sys.argv[1:] == ["--test"]:
        main_test()
    elif not sys.argv[1:]:
        main_audit()
    else:
        sys.exit("Usage: scripts/audit.py [--test]")


if __name__ == "__main__":
    main()
